// Copies the IDLs that `anchor build` produced into typed TS modules the client
// compiles against: from ../target (in the build copy, freshest) or else from
// ../idl (in the repo, pulled there by scripts/build-copy.sh).
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const built = existsSync(join(root, "target", "idl", "arena.json"));
const jsonPath = (n) => (built ? join(root, "target", "idl", `${n}.json`) : join(root, "idl", `${n}.json`));
const typesPath = (n) => (built ? join(root, "target", "types", `${n}.ts`) : join(root, "idl", `${n}.ts`));
const out = join(here, "..", "src", "idl");
// only this build's programs: a retired one's IDL must not linger in the package
rmSync(out, { recursive: true, force: true });
mkdirSync(out);

for (const [name, Type] of [["arena", "Arena"], ["house", "House"]]) {
  const json = readFileSync(jsonPath(name), "utf8");
  writeFileSync(join(out, `${name}-types.ts`), readFileSync(typesPath(name), "utf8"));
  writeFileSync(
    join(out, `${name}.ts`),
    `// Generated by scripts/copy-idl.mjs from solana/idl/${name}.json. Do not edit.\n` +
      `import type { ${Type} } from "./${name}-types.js";\n` +
      `export type { ${Type} };\n` +
      // The JSON is snake_case; the generated type is camelCase. Program()
      // converts at runtime, so the cast is the documented way to type it.
      `export const ${name}Idl = ${json.trim()} as unknown as ${Type};\n`,
  );
}
console.log(`idl (${built ? "target" : "idl"}) -> src/idl/{arena,house}.ts`);
